"""
balance_dataset.py
==================
Creates a balanced train/val/test split from the local s3_cache
WITHOUT copying any files. Instead writes YOLO-compatible image
path list files (train.txt, val.txt, test.txt) and a dataset YAML.

This is instant — no file copying, no disk space wasted.

Usage:
    py -3.11 balance_dataset.py                        # auto cap at smallest class
    py -3.11 balance_dataset.py --max-per-class 34241  # explicit cap
"""

import argparse
import json
import random
from pathlib import Path

# ── Config ────────────────────────────────────────────────────────────────────

CACHE_DIR  = Path("data/s3_cache")
OUTPUT_DIR = Path("data/retail_cv_balanced")
SEED       = 42
SPLITS     = {"train": 0.70, "val": 0.20, "test": 0.10}

CLASS_TO_ID = {
    "No Interest":           0,
    "Picking And Returning": 1,
    "Picking and Putting":   2,
    "Touching":              3,
    "Turning to Shelf":      4,
    "Viewing":               5,
}

# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-per-class", type=int, default=None)
    args = parser.parse_args()

    random.seed(SEED)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Collect valid image paths per class
    print("\nScanning local cache...")
    all_paths: dict[str, list[Path]] = {}
    for cls in CLASS_TO_ID:
        img_dir = CACHE_DIR / cls / "images"
        lbl_dir = CACHE_DIR / cls / "labels"
        if not img_dir.exists():
            print(f"  WARNING: {cls} missing, skipping.")
            continue
        valid = [
            p for p in sorted(img_dir.glob("*.jpg"))
            if (lbl_dir / p.with_suffix(".txt").name).exists()
        ]
        all_paths[cls] = valid
        print(f"  {cls:<25} {len(valid):>6} valid images")

    # Determine cap
    min_count = min(len(v) for v in all_paths.values())
    max_per_class = args.max_per_class or min_count
    print(f"\nCapping at {max_per_class:,} images per class")

    # Build split path lists
    split_lists: dict[str, list[str]] = {"train": [], "val": [], "test": []}
    per_class_stats: dict[str, dict] = {}

    for cls, paths in all_paths.items():
        if len(paths) > max_per_class:
            paths = random.sample(paths, max_per_class)
        else:
            paths = paths.copy()
            random.shuffle(paths)

        n       = len(paths)
        n_train = int(n * SPLITS["train"])
        n_val   = int(n * SPLITS["val"])

        split_lists["train"] += [str(p.resolve()) for p in paths[:n_train]]
        split_lists["val"]   += [str(p.resolve()) for p in paths[n_train:n_train + n_val]]
        split_lists["test"]  += [str(p.resolve()) for p in paths[n_train + n_val:]]

        per_class_stats[cls] = {
            "train": n_train,
            "val":   n_val,
            "test":  n - n_train - n_val,
            "total": n,
        }

    # Shuffle each split so classes are mixed
    for split in split_lists:
        random.shuffle(split_lists[split])

    # Write path list files
    for split, paths in split_lists.items():
        out = OUTPUT_DIR / f"{split}.txt"
        out.write_text("\n".join(paths))
        print(f"  Written {split}.txt  ({len(paths):,} images)")

    # Write dataset YAML
    yaml_content = f"""# CARR Balanced Dataset
# Auto-generated by balance_dataset.py
# Max per class: {max_per_class}

path: {OUTPUT_DIR.resolve().as_posix()}
train: train.txt
val: val.txt
test: test.txt

nc: {len(CLASS_TO_ID)}
names:
"""
    for cls, idx in CLASS_TO_ID.items():
        yaml_content += f"  {idx}: {cls.replace(' ', '_')}\n"

    yaml_path = OUTPUT_DIR / "dataset.yaml"
    yaml_path.write_text(yaml_content)

    # Write summary
    total = sum(len(v) for v in split_lists.values())
    summary = {
        "max_per_class":  max_per_class,
        "total_images":   total,
        "split_counts":   {s: len(v) for s, v in split_lists.items()},
        "per_class":      per_class_stats,
        "class_to_id":    CLASS_TO_ID,
        "dataset_yaml":   str(yaml_path.resolve()),
    }
    (OUTPUT_DIR / "summary.json").write_text(json.dumps(summary, indent=2))

    # Print summary
    print(f"\n{'='*55}")
    print(f" Dataset ready — NO files copied, just path lists")
    print(f"{'='*55}")
    print(f"  train: {len(split_lists['train']):>6,} images")
    print(f"  val:   {len(split_lists['val']):>6,} images")
    print(f"  test:  {len(split_lists['test']):>6,} images")
    print(f"  total: {total:>6,} images")
    print(f"\n  Dataset YAML: {yaml_path.resolve()}")
    print(f"  Use this in training:")
    print(f"  py -3.11 train_carr.py --data {yaml_path.resolve()}")


if __name__ == "__main__":
    main()
